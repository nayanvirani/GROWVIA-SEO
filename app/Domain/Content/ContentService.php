<?php

namespace App\Domain\Content;

use App\Domain\AI\AiService;
use App\Models\ContentBrief;
use App\Models\ContentDraft;
use App\Models\ImageAsset;
use App\Models\Website;
use App\Models\WebsitePage;
use App\Support\ActivityLogger;
use App\Support\Enums\ContentStatus;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

class ContentService
{
    public function __construct(private readonly AiService $ai, private readonly QualityChecker $quality) {}

    public function createBrief(Website $website, array $data): ContentBrief
    {
        $brief = $website->contentBriefs()->create([
            'title' => $data['title'],
            'content_type' => $data['content_type'] ?? 'blog_post',
            'page_id' => $data['page_id'] ?? null,
            'primary_keyword_id' => $data['primary_keyword_id'] ?? null,
            'audience' => $data['audience'] ?? null,
            'intent' => $data['intent'] ?? null,
            'source_notes' => $data['source_notes'] ?? null,
            'status' => ContentStatus::Idea->value,
        ]);
        ActivityLogger::log($website, 'brief.created', $brief);

        return $brief;
    }

    /** AI outline for a brief (IDEA -> BRIEF_DRAFT). */
    public function outlineBrief(ContentBrief $brief): ContentBrief
    {
        $result = $this->ai->run($brief->website, 'content_brief', $this->briefContext($brief));
        $brief->update([
            'outline_json' => [
                'sections' => $result['data']['outline'],
                'questions_for_human' => $result['data']['questions_for_human'] ?? [],
                'suggested_title' => $result['data']['title'],
            ],
            'audience' => $brief->audience ?: ($result['data']['audience'] ?? null),
            'intent' => $brief->intent ?: ($result['data']['intent'] ?? null),
            'status' => ContentStatus::BriefDraft->value,
        ]);

        return $brief;
    }

    /** Generate a full draft from a brief (-> CONTENT_DRAFT). */
    public function generateDraft(ContentBrief $brief): ContentDraft
    {
        $task = $brief->content_type === 'landing_page' ? 'landing_page' : 'blog_draft';
        $context = $this->briefContext($brief) + [
            'outline' => $brief->outline_json['sections'] ?? null,
            'internal_link_candidates' => $this->internalLinkCandidates($brief),
        ];
        $result = $this->ai->run($brief->website, $task, $context);
        $d = $result['data'];

        $draft = $brief->drafts()->create([
            'website_id' => $brief->website_id,
            'type' => $brief->content_type,
            'title' => Str::limit($d['title'], 250, ''),
            'body_markdown' => $d['body_markdown'],
            'meta_title' => Str::limit($d['meta_title'] ?? '', 250, ''),
            'meta_description' => $d['meta_description'] ?? null,
            'slug_suggestion' => Str::slug($d['slug'] ?? $d['title']),
            'faq_json' => $d['faqs'] ?? [],
            'internal_links_json' => $context['internal_link_candidates'],
            'source_pages_json' => array_values(array_filter([$brief->page?->canonical_url])),
            'status' => ContentStatus::ContentDraft->value,
            'provider' => $result['provider'],
            'model' => $result['model'],
            'prompt_version' => $result['prompt_version'],
        ]);
        $draft->update(['quality_flags_json' => array_merge(
            $this->quality->check($draft, $brief->primaryKeyword?->keyword),
            array_map(fn ($c) => ['type' => 'model_flagged_claim', 'severity' => 'high', 'message' => (string) $c], $d['claims_needing_review'] ?? [])
        )]);
        $draft->revisions()->create(['body_markdown' => $draft->body_markdown, 'change_summary' => 'Generated by '.$result['provider']]);
        $brief->update(['status' => ContentStatus::ContentDraft->value]);
        ActivityLogger::log($brief->website, 'draft.generated', $draft, ['provider' => $result['provider'], 'model' => $result['model']]);

        return $draft;
    }

    /** Title/meta variants for an existing crawled page. */
    public function metaSuggestions(Website $website, WebsitePage $page): array
    {
        return $this->ai->run($website, 'meta_suggestions', [
            'page_url' => $page->canonical_url,
            'page_title' => $page->title,
            'current_meta_description' => $page->meta_description,
            'h1' => $page->h1,
            'page_content_excerpt_untrusted' => Str::limit((string) $page->text_excerpt, 2500),
        ])['data']['variants'];
    }

    public function saveDraft(ContentDraft $draft, array $data, ?int $userId): ContentDraft
    {
        if (in_array($draft->status, [ContentStatus::Exported->value, ContentStatus::PublishedExternally->value], true)
            && isset($data['body_markdown'])) {
            // Editing exported content re-opens review.
            $data['status'] = ContentStatus::HumanEdit->value;
        }
        $bodyChanged = isset($data['body_markdown']) && $data['body_markdown'] !== $draft->body_markdown;
        $draft->fill($data);
        if ($bodyChanged || $draft->isDirty(['title', 'meta_title', 'meta_description'])) {
            if (! isset($data['status']) && $draft->status !== ContentStatus::HumanEdit->value) {
                $draft->status = ContentStatus::HumanEdit->value;
            }
            $draft->approved_at = null;
            $draft->approved_by = null;
        }
        $draft->quality_flags_json = $this->quality->check($draft, $draft->brief?->primaryKeyword?->keyword);
        $draft->save();

        if ($bodyChanged) {
            $draft->revisions()->create([
                'user_id' => $userId, 'body_markdown' => $draft->body_markdown,
                'change_summary' => $data['change_summary'] ?? 'Edited',
            ]);
        }
        ActivityLogger::log($draft->website, 'draft.saved', $draft);

        return $draft;
    }

    public function approve(ContentDraft $draft, int $userId): ContentDraft
    {
        $blocking = collect($draft->quality_flags_json ?? [])->where('type', 'placeholder');
        if ($blocking->isNotEmpty()) {
            throw ValidationException::withMessages(['draft' => 'Remove placeholder text marked "[needs human ...]" before approving.']);
        }
        $draft->update([
            'status' => ContentStatus::ApprovedForExport->value,
            'approved_at' => now(),
            'approved_by' => $userId,
        ]);
        ActivityLogger::log($draft->website, 'draft.approved', $draft);

        return $draft;
    }

    /** @return array{filename: string, mime: string, content: string} */
    public function export(ContentDraft $draft, string $format): array
    {
        if (! in_array($draft->status, [ContentStatus::ApprovedForExport->value, ContentStatus::Exported->value,
            ContentStatus::PublishedExternally->value, ContentStatus::PerformanceReview->value], true)) {
            throw ValidationException::withMessages(['draft' => 'Approve the draft before exporting it.']);
        }

        $slug = $draft->slug_suggestion ?: Str::slug($draft->title);
        $faq = collect($draft->faq_json ?? [])->map(fn ($f) => "### {$f['question']}\n\n{$f['answer']}")->implode("\n\n");
        $markdown = "---\ntitle: \"".addslashes((string) $draft->meta_title)."\"\ndescription: \"".addslashes((string) $draft->meta_description)."\"\nslug: {$slug}\n---\n\n"
            .$draft->body_markdown.($faq ? "\n\n## FAQ\n\n{$faq}\n" : '');

        $out = match ($format) {
            'html' => ['filename' => "{$slug}.html", 'mime' => 'text/html', 'content' => $this->html($draft, $faq)],
            'csv' => ['filename' => "{$slug}-metadata.csv", 'mime' => 'text/csv', 'content' => $this->csv([
                ['title', 'meta_title', 'meta_description', 'slug', 'status', 'provider', 'model', 'prompt_version'],
                [$draft->title, $draft->meta_title, $draft->meta_description, $slug, $draft->status, $draft->provider, $draft->model, $draft->prompt_version],
            ])],
            default => ['filename' => "{$slug}.md", 'mime' => 'text/markdown', 'content' => $markdown],
        };

        if ($draft->status === ContentStatus::ApprovedForExport->value) {
            $draft->update(['status' => ContentStatus::Exported->value]);
        }
        $draft->update(['exported_at' => now()]);
        ActivityLogger::log($draft->website, 'draft.exported', $draft, ['format' => $format]);

        return $out;
    }

    public function imageBrief(Website $website, ?ContentDraft $draft, array $data): ImageAsset
    {
        $result = $this->ai->run($website, 'image_brief', [
            'target_keyword' => $data['topic'] ?? $draft?->title,
            'title' => $draft?->title,
            'aspect_ratio' => $data['aspect_ratio'] ?? '16:9',
            'placement' => $data['placement'] ?? 'featured image',
            'audience' => $data['audience'] ?? null,
        ]);
        $d = $result['data'];

        $asset = $website->imageAssets()->create([
            'content_draft_id' => $draft?->id,
            'brief' => $d['brief'],
            'prompt' => $d['prompt'],
            'alt_text' => Str::limit($d['alt_text'], 250, ''),
            'aspect_ratio' => $d['aspect_ratio'] ?? ($data['aspect_ratio'] ?? '16:9'),
            'placement' => $d['placement'] ?? ($data['placement'] ?? null),
            'suggested_filename' => $d['suggested_filename'] ?? null,
            'provider' => $result['provider'],
            'status' => 'brief',
        ]);
        ActivityLogger::log($website, 'image.brief_created', $asset);

        return $asset;
    }

    private function briefContext(ContentBrief $brief): array
    {
        return [
            'title' => $brief->title,
            'target_keyword' => $brief->primaryKeyword?->keyword ?? $brief->title,
            'intent' => $brief->intent,
            'audience' => $brief->audience,
            'source_notes' => $brief->source_notes,
            'page_url' => $brief->page?->canonical_url,
            'page_content_excerpt_untrusted' => $brief->page ? Str::limit((string) $brief->page->text_excerpt, 2500) : null,
        ];
    }

    private function internalLinkCandidates(ContentBrief $brief): array
    {
        $tokens = collect(preg_split('/\W+/', Str::lower(($brief->primaryKeyword?->keyword ?? '').' '.$brief->title)))
            ->filter(fn ($t) => strlen($t) > 3)->unique();

        return WebsitePage::forWebsite($brief->website_id)->where('status_code', 200)->whereNotNull('title')
            ->get(['canonical_url', 'title'])
            ->map(fn ($p) => ['url' => $p->canonical_url, 'title' => $p->title,
                'score' => $tokens->filter(fn ($t) => str_contains(Str::lower($p->title.' '.$p->canonical_url), $t))->count()])
            ->where('score', '>', 0)->sortByDesc('score')->take(5)->values()->all();
    }

    private function html(ContentDraft $draft, string $faq): string
    {
        $body = Str::markdown($draft->body_markdown.($faq ? "\n\n## FAQ\n\n{$faq}" : ''), ['html_input' => 'escape', 'allow_unsafe_links' => false]);

        return "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n<title>".e($draft->meta_title ?: $draft->title)."</title>\n"
            .'<meta name="description" content="'.e($draft->meta_description)."\">\n</head>\n<body>\n{$body}\n</body>\n</html>\n";
    }

    public function csv(array $rows): string
    {
        $h = fopen('php://temp', 'r+');
        foreach ($rows as $row) {
            fputcsv($h, array_map(fn ($v) => is_string($v) && preg_match('/^[=+\-@]/', $v) ? "'".$v : $v, $row), escape: '');
        }
        rewind($h);

        return stream_get_contents($h);
    }
}
